// Regenerates lib/devicon-map.ts from the installed devicon package.
// Run after bumping devicon:  node scripts/gen-devicon-map.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "package.json"));

const devicons = require("devicon/devicon.json");
const css = fs.readFileSync(path.join(root, "node_modules/devicon/devicon.min.css"), "utf8");

const norm = (s) =>
  s
    .toLowerCase()
    .trim()
    .replace(/\+\+/g, "plusplus")
    .replace(/#/g, "sharp")
    .replace(/^\./, "dot")
    .replace(/[^a-z0-9]/g, "");

// Wordmark variants carry the product name as artwork — unusable inside a chip.
const PREFERRED = ["plain", "original", "line"];

// devicon.json declares variants the shipped font does not always carry (awk-plain),
// so the stylesheet is the source of truth for what actually renders.
const exists = (name, variant) => css.includes(`devicon-${name}-${variant}:`);

const variantsOf = (e) =>
  [...new Set([...e.versions.font, ...(e.aliases || []).map((a) => a.alias)])].filter((v) => exists(e.name, v));

const pickVariant = (e) => {
  const available = variantsOf(e);
  return PREFERRED.find((p) => available.includes(p)) ?? available.find((v) => !v.includes("wordmark")) ?? available[0];
};

const luminance = (hex) => {
  const m = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec((hex || "").trim());
  if (!m) return null;
  const full = m[1].length === 3 ? [...m[1]].map((c) => c + c).join("") : m[1];
  const n = parseInt(full, 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

// Dark mode paints --bg-primary as pure black. Only marks that are essentially
// black there (contrast under 1.6:1) drop `colored` and inherit currentColor —
// deliberately narrow, because everything else must keep its brand colour in
// light mode, where it is perfectly legible.
const classFor = (e) => {
  const l = luminance(e.color);
  const mono = l !== null && (l + 0.05) / 0.05 < 1.6;
  return `${e.name}-${pickVariant(e)}${mono ? "" : " colored"}`;
};

const map = {};
// altnames first, so a canonical name always wins a collision ("c" is C, not C++)
for (const e of devicons) for (const alt of e.altnames || []) map[norm(alt)] ??= classFor(e);
for (const e of devicons) map[norm(e.name)] = classFor(e);

const body = Object.keys(map)
  .sort()
  .map((k) => `  ${/^[a-z][a-z0-9]*$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(map[k])},`)
  .join("\n");

const out = path.join(root, "lib/devicon-map.ts");
fs.writeFileSync(
  out,
  `// Generated by scripts/gen-devicon-map.mjs from devicon.json — do not edit by hand.
// Key: tag name normalised by \`normalise()\` in ./devicon.ts.
// Value: the part after "devicon-", plus " colored" unless the brand mark is so dark
// it would disappear on the dark background (then it inherits currentColor).
export const DEVICON_MAP: Record<string, string> = {
${body}
};
`
);

const mono = Object.values(map).filter((v) => !v.includes("colored")).length;
console.log(`lib/devicon-map.ts — ${Object.keys(map).length} keys, ${mono} without \`colored\``);
